import assert from 'node:assert/strict';
import { calculateCargo, DEFAULT_CARGO, paymentEstimate, PAYMENT_RATE } from './calculators.ts';
const base=calculateCargo(DEFAULT_CARGO)!;
assert.equal(base.chargeable,100);assert.equal(base.total,388);
const light=calculateCargo({...DEFAULT_CARGO,weight:20,volume:1})!;
assert.equal(light.chargeable,200);assert.equal(light.freight,720);
const air=calculateCargo({...DEFAULT_CARGO,transport:'air'})!;
assert.equal(air.total,978);assert.equal(air.days,'5–10');
const extras=calculateCargo({...DEFAULT_CARGO,packing:'crate',inspection:true,destination:'spb'})!;
assert.equal(extras.packing,35);assert.equal(extras.inspection,12);assert.equal(extras.destination,45);assert.equal(extras.total,472);
assert.equal(calculateCargo({...DEFAULT_CARGO,weight:0}),null);
assert.equal(calculateCargo({...DEFAULT_CARGO,volume:NaN}),null);
assert.equal(calculateCargo({...DEFAULT_CARGO,packages:1.5}),null);
assert.equal(calculateCargo({...DEFAULT_CARGO,value:-1}),null);
assert.equal(paymentEstimate(4999,'RUB')!.valid,false);
assert.equal(paymentEstimate(5000,'RUB')!.valid,true);
assert.equal(PAYMENT_RATE,12.79);
assert.equal(paymentEstimate(1000,'CNY')!.rub,12790);
assert.ok(Math.abs(paymentEstimate(12790,'RUB')!.cny-1000)<1e-9);
assert.equal(paymentEstimate(Infinity,'RUB'),null);
console.log('Calculator checks passed: volumetric weight, transport, packing, insurance, extras, invalid input and minimum payment.');
